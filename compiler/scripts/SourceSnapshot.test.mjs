const failure = Effect.fnUntraced(
  /** @param {import('effect/Effect').Effect<unknown,{message:string},import('effect/FileSystem').FileSystem>} effect @param {RegExp} expected */
  function* (effect, expected) {
    const result = yield* Effect.result(effect)
    assert.isTrue(Result.isFailure(result))
    if (Result.isFailure(result)) assert.match(result.failure.message, expected)
  },
)

it.effect(
  'exports committed closure rather than modified checkout; rejects changed and extra source',
  () =>
    Effect.gen(function* () {
      const f = yield* fixture()
      yield* f.put('compiler/src/main.silk', '// formatter changed checkout\n')
      yield* f.put('tomledit/src/Command.silk', '// changed dependency checkout\n')
      yield* f.put('silk.toml', '# changed workspace checkout\n')
      const second = join(f.temporary, 'second')
      const receipt = yield* createSnapshot({ repository: f.repository, directory: second })
      assert.strictEqual(receipt.normalizedDigest, f.receipt.normalizedDigest)
      assert.strictEqual(receipt.archiveSha256, f.receipt.archiveSha256)
      assert.isTrue(
        receipt.files.some(({ path }) => path === 'compiler/src/nested/Dependency.silk'),
      )
      assert.isTrue(receipt.files.some(({ path }) => path === 'compiler/silk.toml'))
      yield* f.fs.writeFileString(join(second, 'compiler/src/extra.silk'), 'unrecorded input')
      yield* failure(verifySnapshot({ directory: second }), /Unrecorded snapshot input/)
      yield* f.fs.remove(join(second, 'compiler/src/extra.silk'))
      yield* f.fs.writeFileString(join(second, 'stdlib/silk/num/i32.silk'), 'changed stdlib')
      yield* failure(verifySnapshot({ directory: second }), /Snapshot bytes or mode changed/)
    }).pipe(Effect.scoped, Effect.provide(NodeServices.layer)),
)

it.effect('restores every workspace input and detects dependency and manifest tampering', () =>
  Effect.gen(function* () {
    const f = yield* fixture()
    const restored = join(f.temporary, 'restored')
    const receipt = yield* restoreSnapshot({ artifact: f.snapshot, directory: restored })
    assert.deepStrictEqual(receipt, f.receipt)
    const paths = ['silk.toml', 'tomledit/silk.toml', 'tomledit/src/Command.silk']
    for (const path of paths) {
      const committed = yield* f.fs.readFileString(join(f.repository, path))
      assert.strictEqual(yield* f.fs.readFileString(join(restored, path)), committed)
      assert.strictEqual(receipt.files.find((file) => file.path === path)?.sha256, hash(committed))
      yield* f.fs.writeFileString(join(restored, path), `${committed}\n# changed\n`)
      yield* failure(verifySnapshot({ directory: restored }), /Snapshot bytes or mode changed/)
      yield* f.fs.writeFileString(join(restored, path), committed)
    }
    yield* f.fs.writeFileString(join(restored, 'tomledit/src/Extra.silk'), 'unrecorded dependency')
    yield* failure(verifySnapshot({ directory: restored }), /Unrecorded snapshot input/)
  }).pipe(Effect.scoped, Effect.provide(NodeServices.layer)),
)

const releaseMetadata = Effect.fnUntraced(function* (f, version) {
  const manifest = yield* f.fs.readFileString(join(f.snapshot, 'compiler/silk.toml'))
  const source = yield* f.fs.readFileString(join(f.snapshot, 'compiler/src/ReleaseVersion.silk'))
  return {
    package: 'silk-compiler',
    version,
    tag: `v${version}`,
    prerelease: version.includes('-'),
    commit: f.revision,
    notes: 'Release notes\n',
    toml: `format = 1\nschema = "silk.changes.snapshot"\npackage = "silk-compiler"\nversion = "${version}"\nkind = "${version.includes('-') ? 'dev' : 'stable'}"\ncommit = "${f.revision}"\nfloor = "0.0.0"\n`,
    manifest: manifest.replace('version = "0.1.0"', `version = "${version}"`),
    versionFile: 'src/ReleaseVersion.silk',
    versionSource: source.replace('b"0.1.0"', `b"${version}"`),
  }
})

it.effect(
  'projects stable and dev identities without changing committed inputs and restores exact provenance',
  () =>
    Effect.gen(function* () {
      const f = yield* fixture()
      const baseArchive = yield* f.fs.readFile(join(f.snapshot, 'authored-inputs.tar'))
      const checkoutManifest = yield* f.fs.readFileString(join(f.repository, 'compiler/silk.toml'))
      for (const [index, version] of [
        '0.1.0',
        `0.2.0-dev.7+${f.revision.slice(0, 12)}`,
      ].entries()) {
        const native = yield* releaseMetadata(f, version)
        const input = join(f.temporary, `native-${index}.json`)
        yield* f.fs.writeFileString(input, yield* encodeJson(native))
        const directory = join(f.temporary, `projected-${index}`)
        const projected = yield* projectSnapshot({ base: f.snapshot, snapshot: input, directory })
        assert.strictEqual(projected.sourceCommit, f.revision)
        assert.strictEqual(projected.projection?.baseDigest, f.receipt.normalizedDigest)
        assert.strictEqual(projected.projection?.baseArchiveSha256, f.receipt.archiveSha256)
        assert.strictEqual(projected.projection?.version, version)
        assert.notStrictEqual(projected.normalizedDigest, f.receipt.normalizedDigest)
        assert.strictEqual(projected.stdlibDigest, f.receipt.stdlibDigest)
        assert.strictEqual(
          yield* f.fs.readFileString(join(directory, 'compiler/silk.toml')),
          native.manifest,
        )
        assert.strictEqual(
          yield* f.fs.readFileString(join(directory, 'compiler/src/ReleaseVersion.silk')),
          native.versionSource,
        )
        assert.strictEqual(
          yield* f.fs.readFileString(join(directory, 'tool/src/ReleaseVersion.silk')),
          native.versionSource,
        )
        assert.strictEqual(
          yield* f.fs.readFileString(join(directory, 'compiler/changes-snapshot.toml')),
          native.toml,
        )
        const restored = join(f.temporary, `projected-restored-${index}`)
        // Distribution needs only the receipt and archive, not the base or loose metadata.
        const artifact = join(f.temporary, `artifact-${index}`)
        yield* f.fs.makeDirectory(artifact)
        for (const name of ['input-snapshot.json', 'authored-inputs.tar'])
          yield* f.fs.copyFile(join(directory, name), join(artifact, name))
        assert.deepStrictEqual(yield* restoreSnapshot({ artifact, directory: restored }), projected)
        yield* f.fs.writeFileString(join(restored, 'projection.json'), '{}')
        yield* failure(
          verifySnapshot({ directory: restored }),
          /Projection metadata digest mismatch/,
        )
        yield* f.fs.writeFileString(
          join(directory, 'input-snapshot.json'),
          yield* encodeJson({
            ...projected,
            projection: { ...projected.projection, version: '9.9.9' },
          }),
        )
        yield* failure(
          verifySnapshot({ directory, receipt: projected }),
          /Snapshot receipt changed/,
        )
        yield* failure(verifySnapshot({ directory }), /Projection provenance or overlay mismatch/)
        yield* failure(
          restoreSnapshot({
            artifact: directory,
            directory: join(f.temporary, `tampered-${index}`),
          }),
          /Projection provenance or overlay mismatch/,
        )
      }
      assert.deepStrictEqual(yield* verifySnapshot({ directory: f.snapshot }), f.receipt)
      assert.deepStrictEqual(
        yield* f.fs.readFile(join(f.snapshot, 'authored-inputs.tar')),
        baseArchive,
      )
      assert.strictEqual(
        yield* f.fs.readFileString(join(f.repository, 'compiler/silk.toml')),
        checkoutManifest,
      )
    }).pipe(Effect.scoped, Effect.provide(NodeServices.layer)),
)

it.effect(
  'rejects wrong commits, paths, metadata, or source edits before exporting a projection',
  () =>
    Effect.gen(function* () {
      const f = yield* fixture()
      const native = yield* releaseMetadata(f, `0.2.0-dev.7+${f.revision.slice(0, 12)}`)
      const cases = [
        { commit: 'f'.repeat(40) },
        { package: 'other-package' },
        { tag: 'v0.2.0' },
        { prerelease: false },
        { versionFile: '../changes/src/Command.silk' },
        { versionFile: 'src/main.silk' },
        { manifest: native.manifest.replace('main = "main.silk"', 'main = "other.silk"') },
        { versionSource: `${native.versionSource}// extra source\n` },
        { toml: native.toml.replace(f.revision, 'f'.repeat(40)) },
        { toml: native.toml.replace('kind = "dev"', 'kind = "stable"') },
        { toml: native.toml.replace('kind = "dev"', 'kind = "prerelease"') },
        yield* releaseMetadata(f, '0.2.0-dev.7+000000000000'),
      ]
      for (const [index, changed] of cases.entries()) {
        const input = join(f.temporary, `rejected-${index}.json`)
        yield* f.fs.writeFileString(input, yield* encodeJson({ ...native, ...changed }))
        const directory = join(f.temporary, `rejected-${index}`)
        yield* failure(
          projectSnapshot({ base: f.snapshot, snapshot: input, directory }),
          /Invalid native|Projection may change only|Snapshot TOML|Invalid snapshot TOML/,
        )
        assert.isFalse(yield* f.fs.exists(directory))
      }
      const input = join(f.temporary, 'valid.json')
      yield* f.fs.writeFileString(input, yield* encodeJson(native))
      yield* failure(
        projectSnapshot({
          base: f.snapshot,
          snapshot: input,
          directory: join(f.snapshot, 'nested'),
        }),
        /separate from its immutable inputs/,
      )
      yield* f.fs.writeFileString(
        join(f.snapshot, 'tomledit/src/Command.silk'),
        'changed dependency',
      )
      yield* failure(
        projectSnapshot({
          base: f.snapshot,
          snapshot: input,
          directory: join(f.temporary, 'changed-base'),
        }),
        /Snapshot bytes or mode changed/,
      )
    }).pipe(Effect.scoped, Effect.provide(NodeServices.layer)),
)

