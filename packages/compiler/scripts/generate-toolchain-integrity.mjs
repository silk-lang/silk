import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const sourceRoot = join(packageRoot, 'src')
const outputPath = join(sourceRoot, 'ToolchainIntegrity.generated.ts')

/**
 * The compiler distribution is the compiler's own sources plus the `@silklang/llvm` modules that
 * write its bitcode. The LLVM part is the built `dist` JavaScript because that, not its TypeScript
 * source, is what the compiler executes: hashing llvm sources would pair a new digest with objects
 * emitted by a stale `dist`. Turbo needs no extra input for it because `^build` folds the
 * `@silklang/llvm#build` hash into `@silklang/compiler#build`.
 */
const parts = [
  {
    label: '@silklang/compiler/src',
    root: sourceRoot,
    includes: (name) => name.endsWith('.ts') && name !== 'ToolchainIntegrity.generated.ts',
  },
  {
    label: '@silklang/llvm/dist',
    root: join(packageRoot, '..', 'llvm', 'dist'),
    includes: (name) => name.endsWith('.js'),
  },
]

const sha256 = (bytes) => createHash('sha256').update(bytes).digest()

// Hash only exact file contents, then sort those identities. Absolute paths, checkout layout,
// directory enumeration order, timestamps, and generated output location never enter the result.
const partDigest = async ({ label, root, includes }) => {
  const entries = await readdir(root, { recursive: true, withFileTypes: true }).catch((error) => {
    if (error.code === 'ENOENT')
      throw new Error(`Toolchain identity input ${label} is missing at ${root}; build it first`)
    throw error
  })
  const identities = await Promise.all(
    entries
      .filter((entry) => entry.isFile() && includes(entry.name))
      .map(async (entry) => sha256(await readFile(join(entry.parentPath, entry.name)))),
  )
  identities.sort((left, right) => Buffer.compare(left, right))
  return sha256(Buffer.concat(identities))
}

// Each part contributes its fixed label and a fixed-width digest, so the encoding is unambiguous
// and moving bytes between parts changes the result.
const digest = createHash('sha256')
for (const part of parts) digest.update(`${part.label}\0`).update(await partDigest(part))
const compilerDigest = digest.digest('hex')

const generated = `// Generated by scripts/generate-toolchain-integrity.mjs. Do not edit.\n\nexport const compilerDigest = '${compilerDigest}'\n`
const check = process.argv.includes('--check')
const current = await readFile(outputPath, 'utf8').catch((error) => {
  if (error.code === 'ENOENT') return undefined
  throw error
})
if (check) {
  if (current !== generated)
    throw new Error('Generated toolchain identity is stale; run pnpm toolchain:generate')
} else if (current !== generated) {
  await writeFile(outputPath, generated)
}
